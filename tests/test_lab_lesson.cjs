'use strict';
const assert = require('node:assert/strict');
const lesson = require('../retail_media/web/lesson.js');
const base = {position:3,session:1,block:1,action:2,product_name:'Nova Auriculares Studio',brand:'Nova',cost_cents:0,reward:0,clicked:false,purchase:false,forced_pacing:false,constraint_conflict:false,guidance:{segment:'Tecnología',converted_before:false,remaining_cents:[400,300,200]},candidates:[{action:0,name:'Orgánico',eligible:true,score:.15},{action:2,name:'Nova Auriculares Studio',eligible:true,score:.17},{action:8,name:'Casa Auriculares Studio',eligible:false,score:.99}]};
assert.deepEqual(lesson.playbackPlan('1'),{steps:1,delay:8000,guided:true});
assert.deepEqual(lesson.playbackPlan('8'),{steps:1,delay:15000,guided:true});
assert.equal(lesson.playbackPlan('200').guided,false);
assert.equal(lesson.playbackPlan('200').steps,200);
assert.equal(lesson.playbackPlan('unknown').delay,8000);
const explained=lesson.describe(base,'safe_rl');
assert.match(explained.context,/Tecnología/);
assert.match(explained.reason,/resto de la visita/);
assert.equal(explained.eligible,2);
assert.equal(explained.blocked,1);
assert.equal(explained.comparison.some(c=>c.action===8),false);
assert.match(explained.outcome,/Sin clic/);
assert.match(lesson.describe({...base,forced_pacing:true},'safe_rl').reason,/atrasada/);
assert.match(lesson.describe({...base,constraint_conflict:true},'safe_rl').warning,/pendiente/);
assert.match(lesson.describe({...base,action:0,guidance:{...base.guidance,converted_before:true}},'safe_rl').reason,/ya compró/);
assert.match(lesson.describe(base,'random').reason,/aleatoriamente/);
assert.match(lesson.describe(base,'bid').reason,/CPC/);
assert.match(lesson.describe({...base,clicked:true,cost_cents:120},'safe_rl').outcome,/no hubo compra/);
assert.match(lesson.describe({...base,clicked:true,purchase:true,reward:1},'safe_rl').outcome,/primera compra/);
assert.match(lesson.describe({...base,coverage_exploration:true},'safe_rl').reason,/primera impresión/);
console.log('Lesson explanation and pacing tests passed');
